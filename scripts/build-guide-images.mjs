#!/usr/bin/env node
/**
 * Regenerate src/guide-images.ts (the /guide screenshots, embedded in the
 * Worker as base64 like the brand rasters in src/seo.ts) from a folder of .webp
 * files:
 *
 *     node scripts/build-guide-images.mjs /path/to/folder/of/webp
 *
 * Each file's basename (without .webp) becomes the URL name /guide/<name>.webp.
 * A short content hash is stored next to the bytes and appended to the image
 * URL as ?v=<hash>, so re-shooting a screenshot busts the immutable cache.
 * Update the width/height table in src/guide.ts if a size changes.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: node scripts/build-guide-images.mjs <folder-with-webp>");
  process.exit(1);
}
const files = readdirSync(dir).filter((f) => f.endsWith(".webp")).sort();
if (files.length === 0) {
  console.error("no .webp files found in " + dir);
  process.exit(1);
}
let out =
  "// GENERATED by scripts/build-guide-images.mjs — do not edit by hand.\n" +
  "export interface GuideImage {\n  /** short content hash, used as ?v= for cache busting */\n  hash: string;\n  base64: string;\n}\n\n" +
  "export const GUIDE_IMAGES: Readonly<Record<string, GuideImage>> = {\n";
for (const f of files) {
  const buf = readFileSync(join(dir, f));
  const hash = createHash("sha256").update(buf).digest("hex").slice(0, 8);
  out += `  ${JSON.stringify(f.replace(/\.webp$/, ""))}: {\n    hash: "${hash}",\n    base64:\n      "${buf.toString("base64")}",\n  },\n`;
}
out += "};\n";
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "..", "src", "guide-images.ts"), out);
console.log(`wrote src/guide-images.ts (${files.length} images)`);
